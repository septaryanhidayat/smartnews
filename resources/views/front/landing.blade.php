    <script>
        document.addEventListener('DOMContentLoaded', function() {
            // 1. Reading Scroll Progress Bar
            const scrollMeter = document.getElementById('snScrollMeter');
            window.addEventListener('scroll', () => {
                const totalHeight = document.documentElement.scrollHeight - window.innerHeight;
                if (totalHeight > 0) {
                    const progress = (window.scrollY / totalHeight) * 100;
                    scrollMeter.style.width = progress + '%';
                }
            }, { passive: true });

            // 2. Fade-In Scroll Observer
            const fadeElements = document.querySelectorAll('.sn-fade-init');
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('sn-in');
                    }
                });
            }, { threshold: 0.08 });
            fadeElements.forEach(el => observer.observe(el));

            // 3. FAQ Accordion
            const faqCards = document.querySelectorAll('.sn-faq-card');
            faqCards.forEach(card => {
                const head = card.querySelector('.sn-faq-head');
                head.addEventListener('click', () => {
                    const isActive = card.classList.contains('active');
                    faqCards.forEach(c => c.classList.remove('active'));
                    if (!isActive) {
                        card.classList.add('active');
                    }
                });
            });

            // 4. Sticky Navbar Shadow
            const navbar = document.getElementById('snNavbar');
            window.addEventListener('scroll', () => {
                if (window.scrollY > 20) {
                    navbar.classList.add('scrolled');
                } else {
                    navbar.classList.remove('scrolled');
                }
            }, { passive: true });
        });

        // 5. Checkout Modal
        function openOrderModal(pkgId, pkgName, pkgPrice) {
